@dataclass(frozen=True)
class GlitchParams:
    """One clock-glitch parameter point."""
    width: float
    offset: float
    repeat: int
    ext_offset: int


def now_tag() -> str:
    """Return a timestamp string for output filenames."""
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def elapsed_ms(start: float, end: float) -> float:
    """Return elapsed time in milliseconds."""
    return (end - start) * 1000.0


def parse_float_list(text: str) -> list[float]:
    """Parse a comma-separated list of floats."""
    values = []

    for item in text.split(","):
        item = item.strip()
        if not item:
            continue
        values.append(float(item))

    if not values:
        raise ValueError(f"Empty float list: {text!r}")

    return values


def parse_int_list(text: str) -> list[int]:
    """Parse a comma-separated list of integers."""
    values = []

    for item in text.split(","):
        item = item.strip()
        if not item:
            continue
        values.append(int(item))

    if not values:
        raise ValueError(f"Empty integer list: {text!r}")

    return values


def inclusive_range(start: int, stop: int, step: int) -> list[int]:
    """Return an inclusive integer range."""
    if step <= 0:
        raise ValueError("step must be positive")

    if stop < start:
        raise ValueError("stop must be >= start")

    return list(range(start, stop + 1, step))


def make_output_dir(user_dir: Path | None) -> Path:
    """Create and return the output directory."""
    if user_dir is not None:
        user_dir.mkdir(parents=True, exist_ok=True)
        return user_dir

    out_dir = DATA_DIR / f"coarse_sweep_{now_tag()}"
    out_dir.mkdir(parents=True, exist_ok=True)
    return out_dir


