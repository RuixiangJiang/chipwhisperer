#!/usr/bin/env python3

from __future__ import annotations

import argparse
import csv
import sys
import time
from datetime import datetime
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
EXPERIMENT_DIR = SCRIPT_DIR.parent
DATA_DIR = EXPERIMENT_DIR / "data" / "baseline"

if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from common_cw import (
    list_devices,
    setup_scope_and_target,
    reset_target,
    read_boot_banner,
    flush_target,
    recover_target,
    disconnect,
)
from kyber_target import KyberTarget


def now_tag() -> str:
    """Return a timestamp string for output filenames."""
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def elapsed_ms(start: float, end: float) -> float:
    """Return elapsed time in milliseconds."""
    return (end - start) * 1000.0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run no-glitch Kyber target baseline: K -> E -> T -> C -> D."
    )

    parser.add_argument(
        "--trials",
        type=int,
        default=100,
        help="Number of no-glitch trials to run.",
    )

    parser.add_argument(
        "--clkgen-freq",
        type=float,
        default=7.3728e6,
        help="Target clock generated by ChipWhisperer.",
    )

    parser.add_argument(
        "--adc-samples",
        type=int,
        default=5000,
        help="ADC sample count for scope setup.",
    )

    parser.add_argument(
        "--adc-timeout",
        type=float,
        default=2.0,
        help="ADC timeout for scope setup.",
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Optional CSV output path.",
    )

    parser.add_argument(
        "--stop-on-failure",
        action="store_true",
        help="Stop immediately when a trial fails.",
    )

    return parser.parse_args()


def make_output_path(user_path: Path | None) -> Path:
    """Create the baseline output path."""
    if user_path is not None:
        user_path.parent.mkdir(parents=True, exist_ok=True)
        return user_path

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    return DATA_DIR / f"baseline_no_glitch_{now_tag()}.csv"


def run_one_trial(kt: KyberTarget) -> dict:
    """Run one K -> E -> T -> C -> D trial."""
    row = {
        "trial_id": None,
        "success": False,
        "k_ret": None,
        "e_ret": None,
        "d_ret": None,
        "ss_match": False,
        "ct_len": None,
        "ss_enc_hex": "",
        "ss_dec_hex": "",
        "ct_first32_hex": "",
        "keypair_ms": None,
        "encaps_ms": None,
        "read_ct_ms": None,
        "upload_ct_ms": None,
        "decaps_ms": None,
        "error": "",
    }

    t0 = time.perf_counter()
    k_ret = kt.keypair()
    t1 = time.perf_counter()

    row["k_ret"] = k_ret
    row["keypair_ms"] = elapsed_ms(t0, t1)

    if k_ret != 0:
        raise RuntimeError(f"Keypair failed with return code {k_ret}")

    t0 = time.perf_counter()
    e_ret, ss_enc = kt.encapsulate_target()
    t1 = time.perf_counter()

    row["e_ret"] = e_ret
    row["encaps_ms"] = elapsed_ms(t0, t1)
    row["ss_enc_hex"] = ss_enc.hex()

    if e_ret != 0:
        raise RuntimeError(f"Encapsulation failed with return code {e_ret}")

    t0 = time.perf_counter()
    ct = kt.read_ciphertext()
    t1 = time.perf_counter()

    row["read_ct_ms"] = elapsed_ms(t0, t1)
    row["ct_len"] = len(ct)
    row["ct_first32_hex"] = ct[:32].hex()

    t0 = time.perf_counter()
    kt.upload_ciphertext(ct)
    t1 = time.perf_counter()

    row["upload_ct_ms"] = elapsed_ms(t0, t1)

    t0 = time.perf_counter()
    d_ret, ss_dec = kt.decapsulate()
    t1 = time.perf_counter()

    row["d_ret"] = d_ret
    row["decaps_ms"] = elapsed_ms(t0, t1)
    row["ss_dec_hex"] = ss_dec.hex()

    if d_ret != 0:
        raise RuntimeError(f"Decapsulation failed with return code {d_ret}")

    row["ss_match"] = ss_enc == ss_dec
    row["success"] = bool(row["ss_match"])

    if not row["ss_match"]:
        raise RuntimeError(
            f"Shared secret mismatch: ss_enc={ss_enc.hex()} ss_dec={ss_dec.hex()}"
        )

    return row


def main() -> None:
    args = parse_args()
    output_path = make_output_path(args.output)

    print("Available ChipWhisperer devices:")
    print(list_devices())

    scope = None
    target = None

    rows = []
    success_count = 0
    failure_count = 0

    try:
        scope, target = setup_scope_and_target(
            clkgen_freq=args.clkgen_freq,
            adc_samples=args.adc_samples,
            adc_timeout=args.adc_timeout,
            ss_version="SS_VER_2_1",
        )

        reset_target(scope)
        raw = read_boot_banner(target, num_char=300, timeout=1000)

        print("Raw UART after reset:")
        print(repr(raw))

        flush_target(target)

        kt = KyberTarget(target)

        for trial_id in range(1, args.trials + 1):
            print(f"\n===== Trial {trial_id}/{args.trials} =====")

            row = {
                "trial_id": trial_id,
                "success": False,
                "k_ret": None,
                "e_ret": None,
                "d_ret": None,
                "ss_match": False,
                "ct_len": None,
                "ss_enc_hex": "",
                "ss_dec_hex": "",
                "ct_first32_hex": "",
                "keypair_ms": None,
                "encaps_ms": None,
                "read_ct_ms": None,
                "upload_ct_ms": None,
                "decaps_ms": None,
                "error": "",
            }

            try:
                row.update(run_one_trial(kt))
                row["trial_id"] = trial_id

                success_count += 1
                print(f"Trial {trial_id}: SUCCESS")

            except Exception as exc:
                failure_count += 1
                row["trial_id"] = trial_id
                row["success"] = False
                row["error"] = str(exc)

                print(f"Trial {trial_id}: FAILURE")
                print(f"Reason: {exc}")

                rows.append(row)

                recover_target(scope, target)

                if args.stop_on_failure:
                    break

                continue

            rows.append(row)

        fieldnames = [
            "trial_id",
            "success",
            "k_ret",
            "e_ret",
            "d_ret",
            "ss_match",
            "ct_len",
            "ss_enc_hex",
            "ss_dec_hex",
            "ct_first32_hex",
            "keypair_ms",
            "encaps_ms",
            "read_ct_ms",
            "upload_ct_ms",
            "decaps_ms",
            "error",
        ]

        with output_path.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(rows)

        print("\n===== Summary =====")
        print(f"Total trials: {args.trials}")
        print(f"Successes: {success_count}")
        print(f"Failures: {failure_count}")
        print(f"CSV output: {output_path}")

        if failure_count == 0:
            print("\nSUCCESS: All no-glitch trials matched.")
        else:
            print("\nWARNING: Some no-glitch trials failed.")
            raise SystemExit(1)

    finally:
        disconnect(scope=scope, target=target)


if __name__ == "__main__":
    main()