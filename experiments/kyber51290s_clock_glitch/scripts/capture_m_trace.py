#!/usr/bin/env python3

from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np

SCRIPT_DIR = Path(__file__).resolve().parent
EXPERIMENT_DIR = SCRIPT_DIR.parent
DATA_DIR = EXPERIMENT_DIR / "data" / "traces"

if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from common_cw import (
    list_devices,
    setup_scope_and_target,
    reset_target,
    read_boot_banner,
    flush_target,
    recover_target,
    disconnect,
)
from common_ss2 import validate_response
from kyber_target import KyberTarget


SS_LEN = 32


def now_tag() -> str:
    """Return a timestamp string for output filenames."""
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def elapsed_ms(start: float, end: float) -> float:
    """Return elapsed time in milliseconds."""
    return (end - start) * 1000.0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Capture no-glitch traces for Kyber decapsulation command D."
    )

    parser.add_argument(
        "--trials",
        type=int,
        default=10,
        help="Number of decapsulation traces to capture.",
    )

    parser.add_argument(
        "--clkgen-freq",
        type=float,
        default=7.3728e6,
        help="Target clock generated by ChipWhisperer.",
    )

    parser.add_argument(
        "--adc-samples",
        type=int,
        default=5000,
        help="ADC sample count.",
    )

    parser.add_argument(
        "--adc-timeout",
        type=float,
        default=2.0,
        help="ADC capture timeout in seconds.",
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Output directory for trace files and metadata.",
    )

    parser.add_argument(
        "--stop-on-failure",
        action="store_true",
        help="Stop immediately when a trial fails.",
    )

    parser.add_argument(
        "--save-traces",
        action="store_true",
        help="Save each captured trace as a .npy file.",
    )

    parser.add_argument(
        "--print-trace-preview",
        action="store_true",
        help="Print the first 10 samples of each trace.",
    )

    return parser.parse_args()


def make_output_dir(user_dir: Path | None) -> Path:
    """Create and return output directory."""
    if user_dir is not None:
        user_dir.mkdir(parents=True, exist_ok=True)
        return user_dir

    out_dir = DATA_DIR / f"decaps_trace_{now_tag()}"
    out_dir.mkdir(parents=True, exist_ok=True)
    return out_dir


def get_trace_array(scope) -> np.ndarray:
    """Read the last captured trace from the scope."""
    trace = scope.get_last_trace()
    return np.asarray(trace)


def capture_message_decode_once(scope, target, timeout=60):
    """
    Capture one M-command trace.

    M command:
        input:  empty
        output: 32-byte decoded message m_dec
        response command: 'M'
    """
    row = {
        "capture_timeout": None,
        "trigger_count": None,
        "classification": "",
        "m_dec_hex": "",
        "m_dec_first8_hex": "",
        "trace": None,
        "trace_len": None,
        "trace_min": None,
        "trace_max": None,
        "trace_mean": None,
        "decaps_ms": None,
        "full_response_hex": "",
        "rv_hex": "",
        "error": "",
    }

    flush_target(target)

    scope.arm()

    t0 = time.perf_counter()
    target.simpleserial_write("M", bytearray([]))

    capture_timeout = bool(scope.capture())
    t1 = time.perf_counter()

    row["capture_timeout"] = capture_timeout
    row["decaps_ms"] = elapsed_ms(t0, t1)

    try:
        row["trigger_count"] = int(scope.adc.trig_count)
    except Exception:
        row["trigger_count"] = None

    if capture_timeout:
        row["classification"] = "capture_timeout"
        row["error"] = "Scope capture timed out"
        return row

    try:
        resp = target.simpleserial_read_witherrors(
            "M",
            32,
            glitch_timeout=timeout,
        )

        packet = validate_response(resp, "M", 32)
        m_dec = packet.payload

        row["m_dec_hex"] = m_dec.hex()
        row["m_dec_first8_hex"] = m_dec[:8].hex()
        row["classification"] = "success"

        try:
            row["full_response_hex"] = bytes(resp.get("full_response", b"")).hex()
        except Exception:
            row["full_response_hex"] = repr(resp.get("full_response", ""))

        if packet.rv is not None:
            row["rv_hex"] = packet.rv.hex()

        trace = get_trace_array(scope)

        row["trace"] = trace
        row["trace_len"] = int(len(trace))
        row["trace_min"] = float(np.min(trace)) if len(trace) > 0 else None
        row["trace_max"] = float(np.max(trace)) if len(trace) > 0 else None
        row["trace_mean"] = float(np.mean(trace)) if len(trace) > 0 else None

        return row

    except Exception as e:
        row["classification"] = "exception"
        row["error"] = repr(e)
        return row


def prepare_ciphertext_for_trial(kt: KyberTarget) -> tuple[bytes, bytes]:
    """
    Prepare a valid target-side ciphertext and expected shared secret.

    Flow:
        K -> E -> T -> C

    Returns:
        (expected_ss, ct)
    """
    k_ret = kt.keypair()
    if k_ret != 0:
        raise RuntimeError(f"Keypair failed with return code {k_ret}")

    e_ret, ss_enc = kt.encapsulate_target()
    if e_ret != 0:
        raise RuntimeError(f"Encapsulation failed with return code {e_ret}")

    ct = kt.read_ciphertext()
    kt.upload_ciphertext(ct)

    return ss_enc, ct


def write_metadata(out_dir: Path, args: argparse.Namespace, boot_banner: str) -> None:
    """Write run-level metadata."""
    metadata = {
        "created_at": datetime.now().isoformat(),
        "script": "capture_decaps_trace.py",
        "trials": args.trials,
        "clkgen_freq": args.clkgen_freq,
        "adc_samples": args.adc_samples,
        "adc_timeout": args.adc_timeout,
        "save_traces": args.save_traces,
        "boot_banner_repr": repr(boot_banner),
    }

    with (out_dir / "metadata.json").open("w") as f:
        json.dump(metadata, f, indent=2)


def main() -> None:
    args = parse_args()
    out_dir = make_output_dir(args.output_dir)

    csv_path = out_dir / "decaps_trace_summary.csv"

    print("Available ChipWhisperer devices:")
    print(list_devices())

    print(f"Output directory: {out_dir}")

    scope = None
    target = None

    rows: list[dict[str, Any]] = []
    success_count = 0
    failure_count = 0

    try:
        scope, target = setup_scope_and_target(
            clkgen_freq=args.clkgen_freq,
            adc_samples=args.adc_samples,
            adc_timeout=args.adc_timeout,
            ss_version="SS_VER_2_1",
        )

        reset_target(scope)
        boot_banner = read_boot_banner(target, num_char=300, timeout=1000)

        print("Raw UART after reset:")
        print(repr(boot_banner))

        flush_target(target)
        write_metadata(out_dir, args, boot_banner)

        kt = KyberTarget(target)

        print("Running one warm-up decapsulation capture...")
        expected_ss, ct = prepare_ciphertext_for_trial(kt)

        warmup_row = capture_message_decode_once(
            scope=scope,
            target=target,
            timeout=60,
        )

        print("Warm-up finished.")

        flush_target(target)

        for trial_id in range(1, args.trials + 1):
            print(f"\n===== Trace trial {trial_id}/{args.trials} =====")

            row: dict[str, Any] = {
                "trial_id": trial_id,
                "success": False,
                "capture_timeout": None,
                "trigger_count": None,
                "ct_first32_hex": "",
                "ss_enc_hex": "",
                "trace_file": "",
                "trace_len": None,
                "trace_min": None,
                "trace_max": None,
                "trace_mean": None,
                "decaps_ms": None,
                "full_response_hex": "",
                "rv_hex": "",
                "error": "",
            }

            try:
                expected_ss, ct = prepare_ciphertext_for_trial(kt)

                row["ss_enc_hex"] = expected_ss.hex()
                row["ct_first32_hex"] = ct[:32].hex()

                capture_row = capture_message_decode_once(
                    scope=scope,
                    target=target,
                    timeout=60,
                )

                trace = capture_row.pop("trace", None)
                row.update(capture_row)

                row["success"] = (
                    row.get("classification") == "success"
                    and not row.get("capture_timeout")
                    and not row.get("error")
                    and bool(row.get("m_dec_hex"))
)

                if args.save_traces and trace is not None:
                    trace_file = out_dir / f"trace_{trial_id:04d}.npy"
                    np.save(trace_file, trace)
                    row["trace_file"] = trace_file.name

                if args.print_trace_preview and trace is not None:
                    print("Trace preview:")
                    print(trace[:10])

                if row["success"]:
                    success_count += 1
                    print(
                        f"Trial {trial_id}: SUCCESS "
                        f"trigger_count={row['trigger_count']} "
                        f"trace_len={row['trace_len']} "
                        f"decaps_ms={row['decaps_ms']:.2f}"
                    )
                else:
                    failure_count += 1
                    print(f"Trial {trial_id}: FAILURE")
                    print(f"Reason: {row['error']}")

                    recover_target(scope, target)

                    if args.stop_on_failure:
                        rows.append(row)
                        break

            except Exception as exc:
                failure_count += 1
                row["success"] = False
                row["error"] = str(exc)

                print(f"Trial {trial_id}: FAILURE")
                print(f"Classification: {row.get('classification')}")
                print(f"Reason: {row.get('error')}")

                recover_target(scope, target)

                if args.stop_on_failure:
                    rows.append(row)
                    break

            rows.append(row)

        fieldnames = [
            "trial_id",
            "success",
            "capture_timeout",
            "trigger_count",
            "classification",
            "ct_first32_hex",
            "ss_enc_hex",
            "m_dec_hex",
            "m_dec_first8_hex",
            "trace_file",
            "trace_len",
            "trace_min",
            "trace_max",
            "trace_mean",
            "decaps_ms",
            "full_response_hex",
            "rv_hex",
            "error",
        ]

        with csv_path.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(rows)

        print("\n===== Summary =====")
        print(f"Trials requested: {args.trials}")
        print(f"Successes: {success_count}")
        print(f"Failures: {failure_count}")
        print(f"CSV output: {csv_path}")

        if args.save_traces:
            print("Trace files saved as .npy in the output directory.")

        if failure_count == 0:
            print("\nSUCCESS: All decapsulation traces captured and verified.")
        else:
            print("\nWARNING: Some trace trials failed.")
            raise SystemExit(1)

    finally:
        disconnect(scope=scope, target=target)


if __name__ == "__main__":
    main()